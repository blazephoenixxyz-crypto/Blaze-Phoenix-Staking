#!/usr/bin/env node
// Regenerates the results section of docs/MONTE_CARLO.md from the TSV lines the
// MonteCarloWalk test prints with -vv. Usage:
//   forge test --match-contract MonteCarloWalk -vv | tee mc.log
//   node test/montecarlo/report.mjs mc.log [more.log ...]
// Everything above the <!-- RESULTS --> marker (the pre-registration) is left untouched.
import { readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";

const logs = process.argv.slice(2);
if (logs.length === 0) { console.error("usage: report.mjs <forge -vv log>..."); process.exit(2); }

const S = [], R = [], Q = [], F = []; let total = 0, fails = 0;
for (const f of logs) {
  for (const raw of readFileSync(f, "utf8").split("\n")) {
    const line = raw.trim();
    const c = line.split("\t");
    if (c[0] === "S") S.push({ k: +c[1], j: +c[2], i: +c[3], act: +c[4], diff: BigInt(c[5]), D: BigInt(c[6]), bits: +c[7] });
    else if (c[0] === "R") R.push({ k: +c[1], j: +c[2], i: +c[3], r: BigInt(c[4]) });
    else if (c[0] === "Q") Q.push({ k: +c[1], j: +c[2], seed: c[3], n: +c[4], settled: +c[5], maxDiff: BigInt(c[6]), maxDiffAt: +c[7], maxD: BigInt(c[8]), maxDAt: +c[9], bit1: +c[10], maxR: BigInt(c[11]), maxRAt: +c[12], minR: BigInt(c[13]), loss: BigInt(c[14]), emg: +c[15], span: +c[16] });
    else if (c[0] === "F") F.push(line);
    else if (c[0] === "T") { total += +c[1]; fails += +c[2]; }
  }
}

const dist = (arr, key) => {
  if (arr.length === 0) return { n: 0 };
  const v = arr.map(x => x[key]).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const at = p => v[Math.min(v.length - 1, Math.floor(p * (v.length - 1)))];
  let mi = 0; for (let x = 1; x < arr.length; x++) if (arr[x][key] > arr[mi][key]) mi = x;
  return { n: v.length, min: v[0], med: at(0.5), p99: at(0.99), max: v[v.length - 1], argmax: arr[mi] };
};
const fmt = d => d.n === 0 ? "no samples" : `n=${d.n}, min ${d.min}, median ${d.med}, p99 ${d.p99}, max ${d.max} at (k=${d.argmax.k}, j=${d.argmax.j}, i=${d.argmax.i})`;

const dDiff = dist(S, "diff"), dD = dist(S, "D"), dR = dist(R, "r");
const aboveDust = S.filter(x => BigInt(x.diff) > 10_000_000_000n).length;
const bit1 = S.filter(x => x.bits & 2).length, bit0 = S.filter(x => x.bits & 1).length;
const seqs = Q.length, emg = Q.filter(q => q.emg).length, loss = Q.filter(q => q.loss > 0n).length;
const batches = [...new Set(Q.map(q => q.k))].sort((a, b) => a - b);
const actors = dist(Q, "n"), spans = dist(Q, "span");
const settledTotal = Q.reduce((a, q) => a + q.settled, 0);
const seedsTable = batches.map(k => {
  const q = Q.find(x => x.k === k);
  return `| ${k} | \`${q.seed}\` (sequence 0 of the batch) |`;
}).join("\n");
const span8y = Q.filter(q => q.span >= 252_288_000).length;   // 8 years = 2920 days

let head = "", gitRev = "";
try { gitRev = execSync("git rev-parse --short HEAD", { encoding: "utf8" }).trim(); } catch {}
const md = readFileSync("docs/MONTE_CARLO.md", "utf8");
head = md.split("\n<!-- RESULTS -->\n")[0] + "\n";
const out = `${head}<!-- RESULTS -->
## Results (generated by \`node test/montecarlo/report.mjs\`, tree \`${gitRev}\`)

Logs read: ${logs.map(l => `\`${l.split("/").pop()}\``).join(", ")}. Batches ${batches.join(", ")}; ${seqs} sequences; ${total} actions drawn, ${settledTotal} settled (the rest reverted, which the walk records as a draw). Pre-registered failures: **${fails}**${F.length ? ` (see the F lines below)` : ""}.

| measure | value |
|---|---|
| stakers per sequence | min ${actors.min}, median ${actors.med}, max ${actors.max} |
| simulated span per sequence (s) | min ${spans.min}, median ${spans.med}, max ${spans.max}; ${span8y} sequences reached the end of the 8-year programme |
| sequences with a loss event | ${loss} |
| sequences that opened the emergency | ${emg} |
| actions where bit 0 of auditInvariants was raised (only after an injected loss) | ${bit0} of ${S.length} |
| actions where bit 1 (soft solvency signal) was raised | ${bit1} of ${S.length} |

### Distributions (wei; the maximiser's case replays with \`MC_BATCH=k MC_SEQ=j\`)

| invariant | distribution |
|---|---|
| MC-CONSERVE abs diff (tolerance 1e10; asserted outside a breached emergency, A3) | ${fmt(dDiff)}; ${aboveDust} of ${S.length} samples above the tolerance, every one inside a breached emergency (anywhere else it is a failure, and failures are ${fails}) |
| MC-CLOSED D = scheduled - distributed (damping and reserve cap only; asserted >= 0) | ${fmt(dD)} |
| rounding residue R = distributed - paid - sum(pending) (asserted >= -1e10) | ${fmt(dR)} |

### Seeds actually used

Derived as pre-registered from \`82ac0d0\`; the first sequence seed of each batch is listed so a reader can check the derivation.

| batch k | seed of (k, 0) |
|---|---|
${seedsTable}

${F.length ? "### Failures (unfiltered)\n\n```\n" + F.join("\n") + "\n```\n" : "No pre-registered invariant failed in these batches.\n"}`;
writeFileSync("docs/MONTE_CARLO.md", out);
console.log(`docs/MONTE_CARLO.md regenerated: ${seqs} sequences, ${total} actions, ${fails} failures`);
